#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Validate knowledge-graph/graph.json and emit graph-data.js.

Usage (from the repository root):
    py -3 tools/build_graph_data.py

Why a separate JS file instead of fetch("graph.json")?
    Opening index.html directly with file:// blocks fetch() by CORS,
    but <script src="graph-data.js"> is allowed. So the page loads
    the same data as a plain script, and still works offline.

Checks performed:
    1. node ids are unique;
    2. every edge points at existing nodes and is not a duplicate;
    3. every `doc` path exists on disk (anchor part ignored);
    4. status is one of done / planned;
    5. (col, row) cells are unique, so the static layout cannot overlap.
"""

import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "knowledge-graph", "graph.json")
DST = os.path.join(ROOT, "knowledge-graph", "graph-data.js")

VALID_STATUS = {"done", "planned"}
VALID_TYPES = {"root", "module", "topic", "case"}
VALID_KINDS = {"contains", "precedes", "case"}


def fail(msg):
    print("ERROR: " + msg)
    sys.exit(1)


def main():
    with open(SRC, encoding="utf-8") as f:
        graph = json.load(f)

    nodes = graph["nodes"]
    edges = graph["edges"]
    ids = [n["id"] for n in nodes]

    if len(ids) != len(set(ids)):
        dup = sorted({i for i in ids if ids.count(i) > 1})
        fail("duplicate node ids: %s" % ", ".join(dup))

    cells = {}
    for n in nodes:
        if n["status"] not in VALID_STATUS:
            fail("node %s has unknown status %r" % (n["id"], n["status"]))
        if n["type"] not in VALID_TYPES:
            fail("node %s has unknown type %r" % (n["id"], n["type"]))
        cell = (n["col"], n["row"])
        if cell in cells:
            fail("layout collision at %s: %s vs %s" % (cell, cells[cell], n["id"]))
        cells[cell] = n["id"]
        path = n["doc"].split("#", 1)[0]
        if not os.path.exists(os.path.join(ROOT, path)):
            fail("node %s -> missing doc %s" % (n["id"], path))

    seen = set()
    for e in edges:
        for key in ("from", "to"):
            if e[key] not in ids:
                fail("edge %s -> unknown node %s" % (e, e[key]))
        if e["kind"] not in VALID_KINDS:
            fail("edge %s -> unknown kind %r" % (e, e["kind"]))
        sig = (e["from"], e["to"], e["kind"])
        if sig in seen:
            fail("duplicate edge %s" % (sig,))
        seen.add(sig)

    payload = json.dumps(graph, ensure_ascii=False, indent=2)
    js = (
        "/* Generated by tools/build_graph_data.py -- do not edit by hand.\n"
        "   Source of truth: knowledge-graph/graph.json */\n"
        "window.GRAPH = " + payload + ";\n"
    )
    with open(DST, "w", encoding="utf-8", newline="\n") as f:
        f.write(js)

    done = sum(1 for n in nodes if n["status"] == "done")
    print("OK  %d nodes (%d done, %d planned), %d edges"
          % (len(nodes), done, len(nodes) - done, len(edges)))
    print("WROTE " + os.path.relpath(DST, ROOT))


if __name__ == "__main__":
    main()
